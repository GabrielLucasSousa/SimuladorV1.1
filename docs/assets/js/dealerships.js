// Preenche a busca de concessionária com as da marca informada (ou todas, sem marca)
function populateDealershipOptions(brand) {
  const list = document.getElementById('dealershipOptions');
  if (!list) return;
  const names = DEALERSHIPS_BY_BRAND[brand]
    || [...new Set(Object.values(DEALERSHIPS_BY_BRAND).flat())].sort();
  list.innerHTML = names.map(name => `<option value="${name}"></option>`).join('');
}

document.addEventListener('DOMContentLoaded', () => populateDealershipOptions());
